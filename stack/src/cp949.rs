//! Hangul in CP949, so a mod can name a file or folder in Korean.
//!
//! The client asks for its assets under Korean names, as CP949 bytes that every
//! tool in the chain reads one byte to a character -- `로그` arrives as `·Î±×`.
//! A mod that ships those characters is a mod that unpacks differently on
//! different machines, and a mod that ships the Korean itself names a file the
//! client never asks for. This turns the second into the first as the mod is
//! laid down, so a mod can be written in real Korean, in UTF-8, like any other
//! text.
//!
//! Only Hangul syllables, which is every Korean name the client uses for its
//! directories, jobs and sexes. No crate: the 2,350 syllables KS X 1001 encodes
//! are listed below, and the other 8,822 are placed by UHC's own rule -- in
//! code-point order through lead bytes 0x81-0xC6. `every_syllable_lands_where_cp949_puts_it`
//! pins both halves against values taken from a real codec.

